import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {transform} from 'esbuild';
const source=await readFile('src/services/api.ts','utf8');
const section=source.slice(source.indexOf('const pendingPhoneRoles'),source.indexOf('export const api ='));
let calls=0, complete;
globalThis.phoneRoleDb={from(){return {select(){return this;},eq(){return this;},abortSignal(){return this;},maybeSingle(){calls++;return new Promise(resolve=>{complete=resolve;});}};}};
const {code}=await transform('const supabase=globalThis.phoneRoleDb;\n'+section+'\nexport {lookupPhoneRole};',{loader:'ts',format:'esm'});
const {lookupPhoneRole}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const first=lookupPhoneRole('9000000000'), second=lookupPhoneRole('9000000000');
assert.equal(calls,1);
complete({data:{role:'COLLECTOR'},error:null});
assert.deepEqual(await first,await second);
await Promise.resolve();
const next=lookupPhoneRole('9000000000');
assert.equal(calls,2,'Completed role results must not be reused');
complete({data:null,error:{message:'offline'}});
await assert.rejects(next,/Could not check/);
await Promise.resolve();
const retry=lookupPhoneRole('9000000000');
assert.equal(calls,3,'Failed lookup must allow retry');
complete({data:{role:'RECYCLER'},error:null});
assert.equal((await retry).role,'RECYCLER');
console.log('PASS: in-flight deduplication, no stale role reuse, failed lookup retry. No network or SMS.');
