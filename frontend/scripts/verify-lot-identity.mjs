import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {build} from 'esbuild';
globalThis.crypto ||= webcrypto;
const bundle=await build({entryPoints:['src/utils/lotIdentity.ts'],bundle:true,write:false,format:'esm',platform:'browser'});
const {createLotId,lotReference,districtCode}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const date=new Date(2026,9,8);
const ids=Array.from({length:10000},()=>createLotId('पुणे',date));
assert.equal(new Set(ids).size,ids.length);
assert.equal(new Set(ids.map(lotReference)).size,ids.length);
assert.ok(ids.every(id=>/^EW-PUN-2026-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(id)));
assert.equal(districtCode('लखनऊ'),'LKO'); assert.equal(districtCode('नागपूर'),'NGP'); assert.equal(districtCode(''),'UNK');
for(const legacy of ['EW-LKO-2026-948123','EW-001','EW-aaaaaaaa-0000-4000-8000-000000000001']) assert.equal(lotReference(legacy),legacy);
const a='EW-PUN-2026-aaaaaaaa-0000-4000-8000-000000000001';
const b='EW-PUN-2026-aaaaaaaa-0000-4000-8000-000000000002';
assert.notEqual(lotReference(a),lotReference(b));
assert.equal(lotReference(a),lotReference(JSON.parse(JSON.stringify(a))));
assert.throws(()=>createLotId('Pune',new Date('invalid')));
console.log('PASS: 10k UUID/reference sample, full UUID distinction, legacy IDs, district aliases, deterministic reload and invalid date.');
